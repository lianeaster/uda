# Сума площ із креслення, без побутових приміщень (їхньої площі там немає).
PLAN_AREA = sum(room.get('area', 0) for room in PLAN)


def _directions_label(n):
    if n == len(DIRECTIONS):
        return 'усі напрями'
    if n % 10 == 1 and n % 100 != 11:
        return f'{n} напрям'
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return f'{n} напрями'
    return f'{n} напрямів'


# Де ставити підпис: центр кімнати, рядки назви, площі й «кому служить» по
# вертикалі навколо нього. Вузька кімната отримує лише повернуту площу.
_by_slug = {d['slug']: d for d in DIRECTIONS}
for room in PLAN:
    room.setdefault('name', ' '.join(room['lines']))
    if 'uses' in room:
        room['directions'] = [_by_slug[slug] for slug in room['uses']]
        room['uses_label'] = _directions_label(len(room['uses']))
    rows = len(room['lines']) + ('area' in room) + ('uses' in room)
    room['cx'] = room['x'] + room['w'] / 2
    room['cy'] = room['y'] + room['h'] / 2
    room['text_y'] = room['cy'] - (rows - 1) * 14 + 8
    room['narrow'] = room['w'] < 70

