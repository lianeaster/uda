def modules():
    """Модулі програми по порядку: (позиція, номер, назва, формат)."""
    for position, (code, name, module_format, _items) in enumerate(MODULES, start=1):
        yield position, code, name.rstrip('.'), FORMATS[module_format]


def subjects():
    """Предмети програми по порядку: (позиція, номер, назва, номер модуля, лектори, години)."""
    position = 0
    for module_code, _name, _format, items in MODULES:
        for code, name, lecturers, hours in items:
            position += 1
            yield (position, code, name, module_code, lecturers,
                   None if hours is None else Decimal(str(hours)))
